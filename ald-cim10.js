/* Retrouve le(s) numéro(s) d'ALD (entiers) d'un code CIM10 d'épisode : le code de la table (3 caractères ou plus) doit être le début du code du dossier. */
window.aldFromCim10 = function(code){
  const c = String(code || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
  const out = [];
  Object.keys(window.ALD_CIM10).forEach(k => {
    const n = parseInt(k, 10);
    if(window.ALD_CIM10[k].codes.some(x => c.indexOf(x[0].toUpperCase().replace(/[^A-Z0-9]/g, '')) === 0) && out.indexOf(n) < 0) out.push(n);
  });
  return out;
};
